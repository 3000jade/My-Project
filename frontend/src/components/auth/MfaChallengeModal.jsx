import React, { useState, useRef, useEffect } from 'react';
import { IconShieldCheck, IconX } from '@tabler/icons-react';

export default function MfaChallengeModal({
  isOpen,
  onVerifyCode,
  onResendCode,
  onClose
}) {
  const [digits, setDigits] = useState(['', '', '', '', '', '']);
  const [resendCooldown, setResendCooldown] = useState(60);
  const [isVerifying, setIsVerifying] = useState(false);
  const inputRefs = useRef([]);

  useEffect(() => {
    if (isOpen) {
      setDigits(['', '', '', '', '', '']);
      inputRefs.current[0]?.focus();
    }
  }, [isOpen]);

  useEffect(() => {
    let timer;
    if (isOpen && resendCooldown > 0) {
      timer = setInterval(() => {
        setResendCooldown((prev) => prev - 1);
      }, 1000);
    }
    return () => clearInterval(timer);
  }, [isOpen, resendCooldown]);

  if (!isOpen) return null;

  const handleChange = async (index, val) => {
    const char = val.slice(-1);
    const newDigits = [...digits];
    newDigits[index] = char;
    setDigits(newDigits);

    // Auto advance focus
    if (char && index < 5) {
      inputRefs.current[index + 1]?.focus();
    }

    // Auto-submit if all filled
    const fullCode = newDigits.join('');
    if (fullCode.length === 6 && !newDigits.includes('')) {
      setIsVerifying(true);
      try {
        await onVerifyCode(fullCode);
      } finally {
        setIsVerifying(false);
      }
    }
  };

  const handleKeyDown = (index, e) => {
    if (e.key === 'Backspace' && !digits[index] && index > 0) {
      inputRefs.current[index - 1]?.focus();
    }
  };

  const handleResend = () => {
    if (resendCooldown === 0 && onResendCode) {
      onResendCode();
      setResendCooldown(60);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-md p-4">
      <div
        data-lenis-prevent="true"
        className="w-full max-w-md bg-white rounded-2xl border border-[#D8DFDF] p-6 shadow-2xl relative flex flex-col items-center text-center"
      >
        {onClose && (
          <button
            onClick={onClose}
            aria-label="Close"
            className="absolute top-4 right-4 w-9 h-9 rounded-full bg-white shadow flex items-center justify-center text-[#141717] hover:bg-[#F4F5F4] transition-colors"
          >
            <IconX size={20} />
          </button>
        )}

        <div className="w-14 h-14 rounded-full bg-[#0D4446]/10 text-[#0D4446] flex items-center justify-center mb-4">
          <IconShieldCheck size={32} />
        </div>

        <h3 className="text-[24px] font-bold font-manrope text-[#141717] mb-2">
          Two-Factor Authentication
        </h3>

        <p className="text-[14px] text-[#5C6768] font-inter mb-6">
          Enter the 6-digit security code generated by your authenticator app or sent to your device.
        </p>

        <div className="flex gap-2 sm:gap-3 justify-center mb-6 w-full">
          {digits.map((digit, idx) => (
            <input
              key={idx}
              ref={(el) => (inputRefs.current[idx] = el)}
              type="text"
              inputMode="numeric"
              maxLength={1}
              value={digit}
              onChange={(e) => handleChange(idx, e.target.value)}
              onKeyDown={(e) => handleKeyDown(idx, e.target.value ? e : e)}
              className="w-12 h-14 sm:w-14 sm:h-14 text-center text-[22px] font-mono font-bold border border-[#D8DFDF] rounded-lg bg-[rgba(255,255,255,0.90)] text-[#141717] focus:border-[#0D4446] focus:ring-1 focus:ring-[#0D4446] outline-none transition-colors"
            />
          ))}
        </div>

        {isVerifying && (
          <div className="flex items-center gap-2 mb-4 text-[#0D4446] text-[14px] font-medium font-inter">
            <span className="w-4 h-4 border-2 border-[#0D4446] border-t-transparent rounded-full animate-spin"></span>
            Verifying Code...
          </div>
        )}

        <div className="text-[14px] font-inter text-[#5C6768]">
          Didn't receive a code?{' '}
          <button
            type="button"
            onClick={handleResend}
            disabled={resendCooldown > 0}
            className="text-[#0D4446] font-semibold hover:underline disabled:text-[#8E9A9B] disabled:no-underline"
          >
            {resendCooldown > 0 ? `Resend code in ${resendCooldown}s` : 'Resend code'}
          </button>
        </div>
      </div>
    </div>
  );
}
